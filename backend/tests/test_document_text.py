"""Reading a stored document back into text (gap 12's content reader).

Every test here runs against **real bytes**, not a stub: a PDF built by hand in
this file, a UTF-8 document, and three shapes of rubbish. Stubbing the parser
would have proven that this module calls ``pypdf`` and nothing about whether the
bytes the store holds can be read, which is the only question worth asking.

The hand-built PDF exists because the alternative is a binary fixture committed
to the repository — unreadable in review, and impossible to check that it still
contains what the assertions claim. :func:`_pdf` writes a one-page document with a
correct cross-reference table, so the test can state its content in the source.

The second half of the file drives ``cli extract`` with **no** ``--text-file``:
the parser above is only worth its refusals if the command actually reaches it
with the bytes the store holds, and that path crosses the store, the cipher, the
contract row and the extractor at once.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from cryptography.fernet import Fernet
from sqlalchemy import select
from sqlalchemy.orm import Session, sessionmaker

from app.cli import EXIT_FAILED, EXIT_OK
from app.cli import main as cli_main
from app.core.config import Settings
from app.core.crypto import FieldCipher, build_cipher
from app.core.document_text import (
    DocumentTextUnavailableError,
    UnsupportedDocumentError,
    document_kind,
    extract_document_text,
)
from app.core.documents import build_document_store
from app.db.enums import ContractStatus, FieldName
from app.db.models import Contract, ExtractedField, Tenant
from app.db.session import session_scope
from app.workers.extraction import decrypt_for_review
from app.workers.extractors import PatternExtractor

#: What the generated PDF draws on its page. Chosen to be a line the *pattern*
#: extractor already understands, so one test can follow the value all the way from
#: bytes to a labelled candidate.
PAGE_TEXT = "Expiry date 2026-01-31, contact a.rahman@example.test"


def _pdf_string(value: str) -> str:
    """``value`` as a PDF literal string body.

    ``(``, ``)`` and ``\\`` are the three characters a literal string may not
    contain unescaped; one of the tests below draws an address, and an address
    later given parentheses would otherwise end the string early and turn a
    readable page into a syntax error.
    """
    return value.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def _pdf(stream: str) -> bytes:
    """A minimal but valid one-page PDF drawing ``stream`` in Helvetica.

    Written by hand rather than with a PDF library: a fixture generated by the same
    package under test would prove that ``pypdf`` can read ``pypdf``, and the point
    here is that it can read something this repository did not write. The
    cross-reference offsets are computed, not guessed — a PDF with a wrong xref is
    exactly the corrupt file :func:`extract_document_text` has to refuse.

    The page draws its text as a real text-showing operation — ``BT``/``Tf``/
    ``Td``/``Tj``/``ET`` — because raw content-stream bytes are not text: a parser
    reads the operands of ``Tj``, and bytes that appear in no such operator are
    just tokens it has to discard.
    """
    drawn = f"BT /F1 12 Tf 72 720 Td ({_pdf_string(stream)}) Tj ET".encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"".join(
            [
                f"<< /Length {len(drawn)} >>\nstream\n".encode("ascii"),
                drawn,
                b"\nendstream",
            ]
        ),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets: list[int] = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode("ascii") + body + b"\nendobj\n"

    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("ascii")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("ascii")
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_at}\n".encode(
        "ascii"
    )
    out += b"%%EOF\n"
    return bytes(out)


def test_the_format_is_decided_by_the_bytes_and_not_by_a_name() -> None:
    """No filename and no content type reaches this module, so the magic is all there is."""
    assert document_kind(_pdf("anything")) == "pdf"
    assert document_kind(b"Expiry date 2026-01-31\n") == "text"


def test_a_pdf_becomes_the_text_its_page_draws() -> None:
    extracted = extract_document_text(_pdf(PAGE_TEXT))

    assert extracted.kind == "pdf"
    assert extracted.pages == 1
    assert "Expiry date 2026-01-31" in extracted.text


def test_the_text_it_produces_is_what_the_extractor_reads() -> None:
    """The whole point of the module: its output is extraction's *input*.

    Nothing else joins these two halves, and each one is individually well tested
    — which is exactly the seam where a mismatch (line breaks, encoding, a page
    marker inside a value) would go unnoticed until a real contract failed.
    """
    extracted = extract_document_text(_pdf(PAGE_TEXT))

    candidates = PatternExtractor().extract(extracted.text)
    found = {candidate.field_name: candidate.value for candidate in candidates}

    assert found[FieldName.END_DATE] == "2026-01-31"
    assert found[FieldName.EMAIL] == "a.rahman@example.test"


def test_a_plain_text_document_passes_through_unchanged() -> None:
    """The behaviour ``cli extract --text-file`` already had, now one branch over."""
    text = "Expiry date 2026-01-31\ncontact a.rahman@example.test\n"

    extracted = extract_document_text(text.encode("utf-8"))

    assert extracted.kind == "text"
    assert extracted.pages == 1
    assert extracted.text == text


def test_a_page_with_no_text_layer_is_empty_text_not_a_failure() -> None:
    """A scanned page must not look like a corrupt file.

    "4 pages, no text" and "the contract never stated an email address" are
    different answers, and collapsing them would send a reviewer looking for a
    field that was never read.
    """
    extracted = extract_document_text(_pdf(""))

    assert extracted.pages == 1
    assert extracted.text.strip() == ""


def test_bytes_that_are_neither_a_pdf_nor_text_are_refused() -> None:
    with pytest.raises(UnsupportedDocumentError):
        extract_document_text(b"\xff\xfe\x00\x01binary rubbish\x80\x81")


def test_an_empty_document_is_refused() -> None:
    with pytest.raises(UnsupportedDocumentError):
        extract_document_text(b"")


def test_a_pdf_that_cannot_be_parsed_is_refused_rather_than_crashing() -> None:
    """Uploaded bytes are untrusted input, so a corrupt file is a refusal this module owns."""
    with pytest.raises(DocumentTextUnavailableError):
        extract_document_text(b"%PDF-1.4\nthis is not a cross-reference table\n")


def test_no_refusal_carries_the_document_into_its_message() -> None:
    """A refusal is logged; the bytes are PII, which is why they were sealed."""
    secret = "a.rahman@example.test"
    payload = _pdf(secret)

    # A parse failure over a document that contains an address: the message must
    # name the problem, never the content.
    with pytest.raises(DocumentTextUnavailableError) as excinfo:
        extract_document_text(payload[: len(payload) // 2])

    assert secret not in str(excinfo.value)


# --- the command ----------------------------------------------------------


@pytest.fixture
def store_settings(settings: Settings, tmp_path: Path) -> Settings:
    """Settings that can seal and read a document, rooted in the test's own directory.

    A key every run would otherwise have to invent, and a store path that is
    absolute because production refuses a relative one (``DOCUMENT_STORE_PATH``) —
    the CLI resolves the store from these two fields and nothing else.
    """
    return settings.model_copy(
        update={
            "encryption_key": Fernet.generate_key().decode("ascii"),
            "document_store_path": str(tmp_path / "documents"),
        }
    )


def _contract_with_document(
    session_factory: sessionmaker[Session],
    settings: Settings,
    tenant: Tenant,
    payload: bytes | None,
) -> tuple[int, FieldCipher]:
    """A contract whose ``storage_path`` names a sealed copy of ``payload``.

    ``None`` means a contract ingested as metadata only: a real row, with a real
    id, and no document to read. The cipher is returned because the stored field
    values are sealed with it, so revealing one in an assertion needs the key.
    """
    cipher = build_cipher(settings)
    key = (
        None if payload is None else build_document_store(settings, cipher=cipher).save(payload).key
    )
    with session_scope(session_factory) as session:
        row = Contract(
            tenant_id=tenant.id,
            customer_ref="A. Rahman",
            timezone="UTC",
            status=ContractStatus.ACTIVE,
            storage_path=key,
        )
        session.add(row)
        session.flush()
        return int(row.id), cipher


def _extract(
    session_factory: sessionmaker[Session], settings: Settings, contract_id: int, *flags: str
) -> int:
    """``cli extract`` with no ``--text-file``: the contract's own document, or nothing."""
    return cli_main(
        ["extract", "--contract-id", str(contract_id), *flags],
        settings=settings,
        session_factory=session_factory,
    )


def _fields(session_factory: sessionmaker[Session], contract_id: int) -> list[ExtractedField]:
    with session_scope(session_factory) as session:
        return list(
            session.execute(
                select(ExtractedField).where(ExtractedField.contract_id == contract_id)
            ).scalars()
        )


def test_a_stored_pdf_is_extracted_without_a_text_file(
    session_factory: sessionmaker[Session],
    store_settings: Settings,
    tenant: Tenant,
) -> None:
    """The whole point of gap 12's content reader, end to end.

    ``storage_path`` has been written by an upload since the contracts slice and
    read by nothing but ``has_document``. Here the same key is loaded, decrypted,
    parsed and handed to the extractor — with no operator-supplied text anywhere —
    and the value that lands in a review row comes from the PDF's own page.
    """
    contract_id, cipher = _contract_with_document(
        session_factory, store_settings, tenant, _pdf(PAGE_TEXT)
    )

    code = _extract(session_factory, store_settings, contract_id)

    assert code == EXIT_OK
    by_name = {field.field_name: field for field in _fields(session_factory, contract_id)}
    assert decrypt_for_review(by_name[FieldName.END_DATE], cipher) == "2026-01-31"
    assert decrypt_for_review(by_name[FieldName.EMAIL], cipher) == "a.rahman@example.test"


def test_a_contract_with_no_document_is_refused_rather_than_extracted_empty(
    session_factory: sessionmaker[Session],
    store_settings: Settings,
    tenant: Tenant,
) -> None:
    """ "We never received the document" must not look like "it stated nothing".

    Metadata-only ingestion is a normal state, so this is a refusal the operator
    has to see and act on, not a quiet run that writes no fields.
    """
    contract_id, _cipher = _contract_with_document(session_factory, store_settings, tenant, None)

    code = _extract(session_factory, store_settings, contract_id)

    assert code == EXIT_FAILED
    assert _fields(session_factory, contract_id) == []
